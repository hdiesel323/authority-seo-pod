import { TaskRecord, HandlerContext, TaskHandler } from "./types.js";

/**
 * ============================================================================
 * AUTHORITY NETWORK SEO POD HANDLER
 * ============================================================================
 * Production SEO execution engine for the Authority Network (96+ commercial
 * web properties, PBN syndication nodes, and niche authority portals).
 *
 * Core Capabilities:
 *  1. 2026 AI Search Engine & Web Crawler Governance (robots.txt generation)
 *  2. Schema.org JSON-LD Structured Data Generation
 *  3. On-Page Metadata & OpenGraph Optimization
 *  4. Semantic Entity & LSI Keyword Clustering
 */

export interface SeoRobotsConfig {
  domain: string;
  sitemapUrl?: string;
  allowAiSearch?: boolean;      // Allow Perplexity, OAI-SearchBot, Claude-Web
  allowAiTraining?: boolean;    // Allow GPTBot, CCBot, Bytespider
}

export interface SeoSchemaConfig {
  type: "Organization" | "WebSite" | "Article" | "LocalBusiness" | "FAQPage";
  domain: string;
  name: string;
  description: string;
  url: string;
  details?: Record<string, any>;
}

export interface SeoMetaConfig {
  title: string;
  targetKeyword: string;
  description: string;
  url: string;
}

export class AuthoritySeoPodHandler implements TaskHandler {
  public name = "authority-seo-handler";

  public canHandle(topic: string, _spec: any): boolean {
    return topic.startsWith("seo.") || topic === "task.assigned";
  }

  public async handle(task: TaskRecord, context: HandlerContext): Promise<any> {
    const { podConfig, now, publishEvent } = context;

    console.log(`[${podConfig.id}] Processing SEO task: ${task.taskId} (Topic: ${task.topic})`);

    const spec = task.spec || {};
    const subAction = spec.action || (task.topic.includes(".") ? task.topic.split(".")[1] : "audit");

    let seoResult: any;

    switch (subAction) {
      case "robots":
      case "crawler_policy": {
        seoResult = this.generateRobotsTxt(spec);
        break;
      }
      case "schema": {
        seoResult = this.generateSchemaJsonLd(spec);
        break;
      }
      case "meta":
      case "audit":
      default: {
        seoResult = this.auditAndOptimizeMeta(spec);
        break;
      }
    }

    const payload = {
      completedBy: podConfig.id,
      role: podConfig.role,
      lob: podConfig.lob,
      taskId: task.taskId,
      action: subAction,
      result: seoResult,
      timestamp: now,
    };

    // Broadcast task completion back to the PM Pod via Tincan mesh
    await publishEvent("task.completed", "pod:pm", {
      taskId: task.taskId,
      workerPod: podConfig.id,
      event: "completed",
      result: payload,
      timestamp: now,
    });

    return payload;
  }

  /**
   * Generates 2026 AI Search & Crawler Governance policy
   */
  public generateRobotsTxt(config: SeoRobotsConfig): { robotsTxt: string; policy: string } {
    const domain = config.domain || "example.com";
    const sitemap = config.sitemapUrl || `https://${domain}/sitemap.xml`;
    const allowSearch = config.allowAiSearch ?? true;
    const allowTraining = config.allowAiTraining ?? false;

    const lines: string[] = [
      `# ==============================================================================`,
      `# 2026 AI SEARCH & REVERSE PROXY ROBOTS.TXT`,
      `# Line of Business: Authority Network (Domain: ${domain})`,
      `# Generated by Authority SEO Pod at ${new Date().toISOString()}`,
      `# ==============================================================================`,
      ``,
      `# 1. Standard Web Search Crawlers (Full Access)`,
      `User-agent: Googlebot`,
      `User-agent: Bingbot`,
      `User-agent: Applebot`,
      `User-agent: YandexBot`,
      `User-agent: DuckDuckBot`,
      `Allow: /`,
      ``,
    ];

    if (allowSearch) {
      lines.push(
        `# 2. AI Direct Answer & Citation Engines (Allowed for LLM Referral Visibility)`,
        `User-agent: OAI-SearchBot`,
        `User-agent: PerplexityBot`,
        `User-agent: Claude-Web`,
        `User-agent: Applebot-Extended`,
        `User-agent: Meta-ExternalAgent`,
        `Allow: /`,
        ``
      );
    } else {
      lines.push(
        `# 2. AI Direct Answer Engines (Blocked)`,
        `User-agent: OAI-SearchBot`,
        `User-agent: PerplexityBot`,
        `User-agent: Claude-Web`,
        `Disallow: /`,
        ``
      );
    }

    if (!allowTraining) {
      lines.push(
        `# 3. Model Training Scrapers & Bulk Dataset Crawlers (Blocked)`,
        `User-agent: GPTBot`,
        `User-agent: CCBot`,
        `User-agent: Bytespider`,
        `User-agent: anthropic-ai`,
        `User-agent: ClaudeBot`,
        `User-agent: cohere-ai`,
        `User-agent: Diffbot`,
        `User-agent: FacebookBot`,
        `User-agent: Scrapy`,
        `Disallow: /`,
        ``
      );
    }

    lines.push(
      `# 4. Default Fallback Rules`,
      `User-agent: *`,
      `Disallow: /api/`,
      `Disallow: /admin/`,
      `Disallow: /private/`,
      `Allow: /`,
      ``,
      `# 5. Sitemaps`,
      `Sitemap: ${sitemap}`
    );

    return {
      robotsTxt: lines.join("\n"),
      policy: allowSearch ? "AI Search Engines Permitted (Training Scrapers Gated)" : "Strict Search-Only",
    };
  }

  /**
   * Generates Schema.org JSON-LD structured data
   */
  public generateSchemaJsonLd(config: SeoSchemaConfig): Record<string, any> {
    const type = config.type || "WebSite";
    const name = config.name || "Authority Portal";
    const url = config.url || `https://${config.domain || "example.com"}`;
    const description = config.description || "Leading industry analysis and insights.";

    if (type === "Organization" || type === "LocalBusiness") {
      return {
        "@context": "https://schema.org",
        "@type": type,
        name,
        url,
        description,
        telephone: config.details?.phone || "+1-800-555-0199",
        address: config.details?.address || {
          "@type": "PostalAddress",
          addressLocality: "New York",
          addressRegion: "NY",
          addressCountry: "US",
        },
      };
    }

    if (type === "Article") {
      return {
        "@context": "https://schema.org",
        "@type": "Article",
        headline: name,
        description,
        mainEntityOfPage: {
          "@type": "WebPage",
          "@id": url,
        },
        author: {
          "@type": "Person",
          name: config.details?.author || "Editorial Staff",
        },
        datePublished: new Date().toISOString(),
      };
    }

    return {
      "@context": "https://schema.org",
      "@type": "WebSite",
      name,
      url,
      description,
      potentialAction: {
        "@type": "SearchAction",
        target: `${url}/search?q={search_term_string}`,
        "query-input": "required name=search_term_string",
      },
    };
  }

  /**
   * Performs on-page metadata optimization and length checks
   */
  public auditAndOptimizeMeta(config: SeoMetaConfig): Record<string, any> {
    const rawTitle = config.title || "Authority Portal - Industry Insights";
    const rawDesc = config.description || "Discover verified analysis and expert guides.";
    const keyword = config.targetKeyword || "commercial finance";

    // Optimization rules: Title <= 60 chars, Desc <= 155 chars
    let optimizedTitle = rawTitle;
    if (optimizedTitle.length > 60) {
      optimizedTitle = optimizedTitle.slice(0, 57) + "...";
    }

    let optimizedDesc = rawDesc;
    if (optimizedDesc.length > 155) {
      optimizedDesc = optimizedDesc.slice(0, 152) + "...";
    }

    const keywordInTitle = optimizedTitle.toLowerCase().includes(keyword.toLowerCase());
    const keywordInDesc = optimizedDesc.toLowerCase().includes(keyword.toLowerCase());

    return {
      title: {
        value: optimizedTitle,
        length: optimizedTitle.length,
        optimalLength: optimizedTitle.length <= 60,
        hasKeyword: keywordInTitle,
      },
      description: {
        value: optimizedDesc,
        length: optimizedDesc.length,
        optimalLength: optimizedDesc.length <= 155,
        hasKeyword: keywordInDesc,
      },
      openGraph: {
        "og:title": optimizedTitle,
        "og:description": optimizedDesc,
        "og:type": "website",
        "og:url": config.url || "https://example.com",
      },
      score: (keywordInTitle ? 40 : 0) + (keywordInDesc ? 30 : 0) + (optimizedTitle.length <= 60 ? 15 : 0) + (optimizedDesc.length <= 155 ? 15 : 0),
    };
  }
}

export const activeHandler: TaskHandler = new AuthoritySeoPodHandler();
export { AuthoritySeoPodHandler as DefaultPodHandler };
